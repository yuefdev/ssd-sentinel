// Generates src/i18n_backend_data.ts: the Turkish -> English table the UI uses for strings that
// come back from the Rust backend.
//
// Sources, merged in this order (later ones never override earlier ones):
//   1. tools/backend_i18n_manual.mjs         hand-written pairs
//   2. every bilingual Rust call site          core.t(tr, en), phase_bi(core, tr, en),
//                                              pick(en, tr, en_str), `if en { EN } else { TR }`
//
// Usage:  node tools/gen_backend_i18n.mjs          (writes the file)
//         node tools/gen_backend_i18n.mjs --check  (exit 1 when the file is stale)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MANUAL_PAIRS } from "./backend_i18n_manual.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
export const repoRoot = path.resolve(here, "..");
export const rustDir = path.join(repoRoot, "src-tauri", "src");
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
export const dataFile = path.join(repoRoot, "src", "i18n_backend_data.ts");

export const TURKISH = /[\u00e7\u011f\u0131\u00f6\u015f\u00fc\u00c7\u011e\u0130\u00d6\u015e\u00dc]/;
const LIT = String.raw`"((?:[^"\\]|\\.)*)"`;
const FMT = String.raw`(?:&?format!\(\s*)?`;
const IS_EN = String.raw`(?:en|core\.is_en\(\)|self\.is_en\(\)|lang\s*==\s*"en")`;

const unescapeRust = (s) => s.replace(/\\"/g, '"').replace(/\\\\/g, "\\");

/** Rust source without its `#[cfg(test)]` tail, with LF line endings. */
export function productionSource(file) {
  let src = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const cut = src.search(/#\[cfg\(test\)\]/);
  if (cut > 0) src = src.slice(0, cut);
  return src;
}

export function rustFiles() {
  return fs
    .readdirSync(rustDir)
    .filter((f) => f.endsWith(".rs"))
    .map((f) => path.join(rustDir, f));
}

const countPlaceholders = (s) => (s.match(/\{[^}]*\}/g) || []).length;

export function collectRustPairs() {
  const regs = [
    {
      re: new RegExp(
        String.raw`(?:phase_bi\(\s*core,|\.t\(|pick\(\s*(?:en|self\.is_en\(\)|core\.is_en\(\)|lang == "en"),)\s*` +
          FMT + LIT + String.raw`[^"]*?,\s*` + FMT + LIT,
        "g",
      ),
      tr: 1,
      en: 2,
    },
    {
      re: new RegExp(
        String.raw`if\s+` + IS_EN + String.raw`\s*\{\s*` + FMT + LIT + String.raw`[^"]*?\}\s*else\s*\{\s*` + FMT + LIT,
        "g",
      ),
      tr: 2,
      en: 1,
    },
    {
      re: new RegExp(String.raw`\(\s*` + LIT + String.raw`,\s*` + LIT + String.raw`,\s*"(?:bad|warning|ok)"\s*,?\s*\)`, "g"),
      tr: 1,
      en: 2,
    },
  ];
  const pairs = new Map();
  for (const file of rustFiles()) {
    const src = productionSource(file);
    for (const { re, tr, en } of regs) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(src))) {
        const t = unescapeRust(m[tr]);
        const e = unescapeRust(m[en]);
        if (t === e || TURKISH.test(e)) continue;
        if (countPlaceholders(t) !== countPlaceholders(e)) continue;
        if (e.length > t.length * 4 || t.length > e.length * 4) continue;
        if (!pairs.has(t)) pairs.set(t, e);
      }
    }
  }
  return pairs;
}

export function buildPairs() {
  const merged = new Map();
  for (const [t, e] of MANUAL_PAIRS) if (!merged.has(t)) merged.set(t, e);
  for (const [t, e] of collectRustPairs()) if (!merged.has(t)) merged.set(t, e);
  return [...merged.entries()].sort((a, b) => a[0].localeCompare(b[0], "en"));
}

export function renderDataFile(pairs) {
  const rows = pairs.map(([t, e]) => `  [${JSON.stringify(t)}, ${JSON.stringify(e)}],`).join("\n");
  return (
    "// AUTO-GENERATED by tools/gen_backend_i18n.mjs - do not edit by hand.\n" +
    "// Regenerate with `npm run gen:i18n` after changing Rust strings or tools/backend_i18n_manual.mjs.\n" +
    "// Turkish backend text -> English, used by src/i18n_backend.ts at the UI boundary.\n" +
    "export const BACKEND_PAIRS: readonly (readonly [string, string])[] = [\n" +
    rows +
    "\n];\n"
  );
}

/** Every Turkish string literal in production Rust code: [file, line, text]. */
export function rustTurkishLiterals() {
  const out = [];
  for (const file of rustFiles()) {
    const src = productionSource(file);
    const re = /"((?:[^"\\\n]|\\.)*)"/g;
    let m;
    while ((m = re.exec(src))) {
      const text = unescapeRust(m[1]);
      if (!TURKISH.test(text)) continue;
      const line = src.slice(0, m.index).split("\n").length;
      out.push([path.basename(file), line, text]);
    }
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = renderDataFile(buildPairs());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(dataFile) ? fs.readFileSync(dataFile, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== rendered) {
      console.error("src/i18n_backend_data.ts is stale. Run: npm run gen:i18n");
      process.exit(1);
    }
    console.log("i18n backend table is up to date.");
  } else {
    fs.writeFileSync(dataFile, rendered);
    console.log(`Wrote ${path.relative(repoRoot, dataFile)} (${buildPairs().length} pairs).`);
  }
}

/** Returns a predicate: is this Turkish text covered by the translation table? */
export function buildMatcher(pairs) {
  const exact = new Set();
  const patterns = [];
  for (const [tr] of pairs) {
    if (!tr.includes("{")) {
      exact.add(tr);
      continue;
    }
    let source = "";
    let last = 0;
    for (const m of tr.matchAll(/\{[^{}]*\}/g)) {
      source += escapeRe(tr.slice(last, m.index)) + "(.+?)";
      last = m.index + m[0].length;
    }
    source += escapeRe(tr.slice(last));
    patterns.push(new RegExp("^" + source + "$", "s"));
  }
  const one = (text) => exact.has(text) || patterns.some((re) => re.test(text));
  return (text) => {
    if (one(text)) return true;
    const parts = text.split(/(?<=[.;!?])\s+/);
    return parts.length > 1 && parts.every(one);
  };
}
